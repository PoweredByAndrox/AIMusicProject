def make_other_guide_preset(base_preset: dict[str, Any], candidate: dict[str, Any], preset_name: str) -> dict[str, Any]:
    preset = deepcopy(base_preset)
    preset["name"] = preset_name
    preset["description"] = (
        f"Autogenerated other-guide search preset: {candidate['label']}. "
        "Search is intentionally narrow and changes only the rebuilt `other` and its tandem guide behavior."
    )
    preset["targets"] = ["vocals", "other", "instrumental_mix"]

    phases: list[dict[str, Any]] = []
    for phase in preset.get("phases", []):
        phase_id = phase.get("id")
        if phase_id.startswith("lyrics_"):
            continue

        new_phase = deepcopy(phase)
        if phase_id == "tandem_cleanup":
            filtered_steps: list[dict[str, Any]] = []
            for step in new_phase.get("steps", []):
                stem = step.get("stem")
                if stem not in {"vocals", "other", "bs_instrumental_seed", "instrumental_mix"}:
                    continue
                if stem == "other":
                    step["task"] = "other_residual_rebuild"
                    step["input_bus"] = "demucs_instrumental_mix"
                    step["rebuild_profile"] = candidate["rebuild_profile"]
                    step["build_from"] = {
                        "include": [
                            "demucs_drums",
                            "demucs_bass",
                            "demucs_guitar",
                            "demucs_piano",
                            "demucs_other",
                            "vocals",
                            "bs_vocals",
                        ]
                    }
                    step.pop("recipe", None)
                if stem == "instrumental_mix":
                    step["other_detail_profile"] = candidate["other_detail_profile"]
                    if candidate.get("other_detail_weights"):
                        step["other_detail_weights"] = deepcopy(candidate["other_detail_weights"])
                    else:
                        step.pop("other_detail_weights", None)
                    step["build_from"] = {
                        "include": [
                            "bs_instrumental_mix",
                            "bs_resurrected_instrumental_mix",
                            "vocals",
                            "bs_vocals",
                            "other",
                        ]
                    }
                filtered_steps.append(step)
            new_phase["steps"] = filtered_steps
        elif phase_id == "final_polish":
            filtered_steps = []
            for step in new_phase.get("steps", []):
                stem = step.get("stem")
                if stem not in {"vocals", "instrumental_mix"}:
                    continue
                if stem == "instrumental_mix":
                    step["recipe"] = candidate["final_recipe"]
                filtered_steps.append(step)
            new_phase["steps"] = filtered_steps
        phases.append(new_phase)

    preset["phases"] = phases
    return preset


def run_search(
    *,
    root: Path,
    base_job_id: str,
    max_candidates: int,
    poll_sec: float,
    wait_idle: bool,
    output_dir: Path | None = None,
    search_id: str | None = None,
    reference_instrumental_path: Path | None = None,
    force_reference_target: bool = False,
) -> dict[str, str]:
    root = root.resolve()
    base_job = read_job(root, base_job_id)
    resolved_reference = reference_instrumental_path.resolve() if reference_instrumental_path else None
    base_report = analyze_job(
        root,
        base_job_id,
        reference_instrumental_path=resolved_reference,
        force_reference_target=force_reference_target,
    )
    write_report(root, base_report)
    focus_windows = base_report.get("focus_windows", [])

    resolved_search_id = search_id or (time.strftime("%Y%m%d_%H%M%S") + "_" + uuid.uuid4().hex[:6])
    out_dir = output_dir.resolve() if output_dir else (root / ".tmp" / "other-guide-search" / resolved_search_id)
    generated_dir = out_dir / "generated_presets"
    out_dir.mkdir(parents=True, exist_ok=True)
    generated_dir.mkdir(parents=True, exist_ok=True)

    results: list[dict[str, Any]] = []
    submitted_jobs: set[str] = set()
    candidates = OTHER_GUIDE_CANDIDATES[: max(1, max_candidates)]

    for candidate in candidates:
        if wait_idle:
            wait_until_idle(root, submitted_jobs, poll_sec)

        preset_name = f"otherguide_{resolved_search_id}_{candidate['slug']}"
        preset_data = make_other_guide_preset(base_job["preset"], candidate, preset_name)
        archive_generated_preset(generated_dir, preset_name, preset_data)

        payload = build_request_from_job(
            base_job,
            preset_name,
            resolved_search_id,
            candidate["slug"],
            enable_lyrics=False,
            preset_override=preset_data,
        )
        created_job = api_request("POST", "/api/v1/jobs", payload)
        job_id = created_job["job_id"]
        submitted_jobs.add(job_id)
        print(f"[submit] {candidate['slug']} -> {job_id}", flush=True)

        finished_job = wait_for_job(job_id, poll_sec)
        if finished_job["status"] != "completed":
            results.append(
                {
                    "candidate": candidate,
                    "job_id": job_id,
                    "status": finished_job["status"],
                    "score": float("-inf"),
                    "issues": ["job_failed"],
                    "metrics": {},
                    "score_breakdown": {},
                    "report_path": None,
                    "mode": "coarse",
                }
            )
            continue

        report = analyze_job(
            root,
            job_id,
            focus_windows=focus_windows,
            reference_instrumental_path=resolved_reference,
            force_reference_target=force_reference_target,
        )
        report_path, _ = write_report(root, report)
        results.append(summarize_result(candidate, finished_job, report, report_path, mode="coarse"))

    json_path, md_path = write_search_report(out_dir, resolved_search_id, base_job, base_report, results)
    return {"search_id": resolved_search_id, "json": str(json_path), "markdown": str(md_path)}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--base-job", required=True)
    parser.add_argument("--max-candidates", type=int, default=4)
    parser.add_argument("--poll-sec", type=float, default=10.0)
    parser.add_argument("--search-id", default=None)
    parser.add_argument("--output-dir", type=Path, default=None)
    parser.add_argument("--wait-until-idle", action="store_true", default=True)
    parser.add_argument("--skip-wait-until-idle", dest="wait_until_idle", action="store_false")
    parser.add_argument("--reference-instrumental", type=Path, default=None)
    parser.add_argument("--force-reference-target", action="store_true")
    args = parser.parse_args()

    result = run_search(
        root=args.root,
        base_job_id=args.base_job,
        max_candidates=args.max_candidates,
        poll_sec=args.poll_sec,
        wait_idle=args.wait_until_idle,
        output_dir=args.output_dir,
        search_id=args.search_id,
        reference_instrumental_path=args.reference_instrumental,
        force_reference_target=args.force_reference_target,
    )
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(130)
