def read_job(project_root: Path, job_id: str) -> dict[str, Any]:
    path = project_root / "data" / "jobs" / job_id / "job.json"
    return json.loads(path.read_text(encoding="utf-8"))


def is_stale_queued_job(project_root: Path, job: dict[str, Any], stale_seconds: float = 900.0) -> bool:
    if job.get("status") != "queued":
        return False
    if job.get("run_log"):
        return False
    job_file = project_root / "data" / "jobs" / job["job_id"] / "job.json"
    if not job_file.exists():
        return False
    age = time.time() - job_file.stat().st_mtime
    return age > stale_seconds


def api_request(method: str, path: str, payload: dict[str, Any] | None = None) -> dict[str, Any]:
    url = f"{API_BASE}{path}"
    data = None
    headers = {}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    req = request.Request(url, method=method, data=data, headers=headers)
    try:
        with request.urlopen(req, timeout=60) as response:
            body = response.read().decode("utf-8")
            return json.loads(body) if body else {}
    except error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"API {method} {path} failed: {exc.code} {detail}") from exc


def wait_until_idle(project_root: Path, excluded_job_ids: set[str], poll_sec: float) -> None:
    while True:
        jobs = api_request("GET", "/api/v1/jobs").get("jobs", [])
        active = [
            job
            for job in jobs
            if job.get("status") in ACTIVE_STATUSES and job.get("job_id") not in excluded_job_ids
            and not is_stale_queued_job(project_root, job)
        ]
        if not active:
            return
        summary = ", ".join(f"{job['job_id']}:{job['status']}:{job['request']['preset_name']}" for job in active[:4])
        print(f"[wait-idle] active jobs: {summary}", flush=True)
        time.sleep(poll_sec)


def wait_for_job(job_id: str, poll_sec: float) -> dict[str, Any]:
    while True:
        job = api_request("GET", f"/api/v1/jobs/{job_id}")
        status = str(job.get("status", "")).lower()
        print(f"[job] {job_id} -> {status}", flush=True)
        if status in {"completed", "failed"}:
            return job
        time.sleep(poll_sec)


def make_search_preset(
    base_preset: dict[str, Any],
    candidate: dict[str, Any],
    preset_name: str,
    *,
    include_lyrics: bool,
) -> dict[str, Any]:
    preset = deepcopy(base_preset)
    preset["name"] = preset_name
    if include_lyrics:
        preset["description"] = (
            f"Autogenerated tandem validation preset: {candidate['label']}. "
            "Used by analyzer-guided search for full pipeline validation with lyrics drift penalty."
        )
    else:
        preset["description"] = (
            f"Autogenerated tandem search preset: {candidate['label']}. "
            "Lyrics phases are stripped to speed up ranking; search focuses on instrumental bleed, warble, and vocal clarity."
        )
        preset["targets"] = ["vocals", "other", "instrumental_mix"]

    phases: list[dict[str, Any]] = []
    for phase in preset.get("phases", []):
        phase_id = phase.get("id")
        if phase_id == "dual_extract":
            phases.append(deepcopy(phase))
            continue
        if phase_id == "tandem_cleanup":
            new_phase = deepcopy(phase)
            filtered_steps = []
            for step in new_phase.get("steps", []):
                stem = step.get("stem")
                if not include_lyrics and stem not in {"vocals", "other", "bs_instrumental_seed", "instrumental_mix"}:
                    continue
                if stem == "other":
                    step["recipe"] = candidate["other_recipe"]
                if stem == "instrumental_mix":
                    step["hybrid_profile"] = candidate["hybrid_profile"]
                filtered_steps.append(step)
            new_phase["steps"] = filtered_steps
            phases.append(new_phase)
            continue
        if phase_id == "final_polish":
            new_phase = deepcopy(phase)
            filtered_steps = []
            for step in new_phase.get("steps", []):
                stem = step.get("stem")
                if not include_lyrics and stem not in {"vocals", "instrumental_mix"}:
                    continue
                if stem == "instrumental_mix":
                    if candidate["final_recipe"]:
                        step["recipe"] = candidate["final_recipe"]
                        filtered_steps.append(step)
                    continue
                filtered_steps.append(step)
            new_phase["steps"] = filtered_steps
            if filtered_steps:
                phases.append(new_phase)
            continue
        if not include_lyrics and phase_id.startswith("lyrics_"):
            continue
        phases.append(deepcopy(phase))

    preset["phases"] = phases
    return preset


def archive_generated_preset(archived_dir: Path, preset_name: str, preset_data: dict[str, Any]) -> Path:
    archive_path = archived_dir / f"{preset_name}.yaml"
    text = json.dumps(preset_data, indent=2, ensure_ascii=False)
    archive_path.write_text(text, encoding="utf-8")
    return archive_path


def build_request_from_job(
    base_job: dict[str, Any],
    preset_name: str,
    search_id: str,
    candidate_slug: str,
    *,
    enable_lyrics: bool,
    preset_override: dict[str, Any],
) -> dict[str, Any]:
    req = base_job["request"]
    return {
        "track_name": req["track_name"],
        "input_path": req["input_path"],
        "preset_name": preset_name,
        "preset_override": preset_override,
        "notes": f"auto-search {search_id} {candidate_slug}",
        "enable_lyrics": enable_lyrics,
        "lyrics_language": req.get("lyrics_language"),
        "lyrics_reference_path": req.get("lyrics_reference_path"),
    }


def summarize_result(
    candidate: dict[str, Any],
    job: dict[str, Any],
    report: dict[str, Any],
    report_path: Path,
    *,
    mode: str,
    previous: dict[str, Any] | None = None,
) -> dict[str, Any]:
    summary = report["summary"]
    stems = report["stems"]
    local_windows = report.get("segment_local") or []
    result = previous or {
        "candidate": candidate,
        "status": job["status"],
        "job_id": job["job_id"],
        "score": report["score"]["composite_score"],
        "issues": report.get("issues", []),
        "metrics": {},
        "score_breakdown": report["score"],
        "report_path": str(report_path),
        "mode": mode,
    }

    target = {
        "job_id": job["job_id"],
        "status": job["status"],
        "score": report["score"]["composite_score"],
        "issues": report.get("issues", []),
        "metrics": {
            "final_mix_vocal_bleed_db": round(summary["final_mix_vocal_bleed_db"], 6),
            "demucs_mix_vocal_bleed_db": round(summary["demucs_mix_vocal_bleed_db"], 6),
            "warble_centroid_ratio": round(summary["other_warble_ratio"]["centroid_std_ratio"], 6),
            "warble_hi4_ratio": round(summary["other_warble_ratio"]["hi4_std_ratio"], 6),
            "warble_flux_ratio": round(summary["other_warble_ratio"]["flux_ratio"], 6),
            "final_source_corr": round(stems["instrumental_mix"]["source_similarity"]["source_similarity_corr"], 6),
            "final_diff_vs_source_rms_db": round(stems["instrumental_mix"]["source_similarity"]["diff_vs_source_rms_db"], 6),
            "openness_centroid_delta_hz": round(summary["demucs_mix_dullness_delta"]["centroid_hz"], 6),
            "openness_hi4_delta": round(summary["demucs_mix_dullness_delta"]["hi4_ratio"], 6),
            "lyrics_coverage_ratio": round(float((summary.get("lyrics_drift") or {}).get("coverage_ratio", 0.0)), 6),
            "lyrics_focus_ratio": round(float((summary.get("lyrics_drift") or {}).get("focus_ratio", 0.0)), 6),
            "lyrics_high_activity_coverage_ratio": round(
                float((summary.get("lyrics_drift") or {}).get("high_activity_coverage_ratio", 0.0)),
                6,
            ),
            "reference_usable": bool((summary.get("reference_compare") or {}).get("usable", False)),
            "reference_diff_vs_rms_db": round(
                float(((summary.get("reference_compare") or {}).get("final") or {}).get("diff_vs_reference_rms_db", 0.0)),
                6,
            ),
            "reference_corr": round(
                float(((summary.get("reference_compare") or {}).get("final") or {}).get("corr", 0.0)),
                6,
            ),
        },
        "score_breakdown": report["score"],
        "report_path": str(report_path),
        "worst_windows": local_windows[:3],
    }

    if mode == "coarse":
        result.update(target)
        result["coarse"] = target
        result["mode"] = "coarse"
    else:
        result["validation"] = target
        result["mode"] = "validated"
        result["job_id"] = job["job_id"]
        result["status"] = job["status"]
        result["score"] = target["score"]
        result["issues"] = target["issues"]
        result["metrics"] = target["metrics"]
        result["score_breakdown"] = target["score_breakdown"]
        result["report_path"] = target["report_path"]
        result["worst_windows"] = target["worst_windows"]
    return result


def write_search_report(
    out_dir: Path,
    search_id: str,
    base_job: dict[str, Any],
    base_report: dict[str, Any],
    results: list[dict[str, Any]],
) -> tuple[Path, Path]:
    ordered = sorted(results, key=lambda item: item.get("score", float("-inf")), reverse=True)
    payload = {
        "search_id": search_id,
        "base_job_id": base_job["job_id"],
        "base_preset_name": base_job["request"]["preset_name"],
        "input_path": base_job["request"]["input_path"],
        "focus_windows": base_report.get("focus_windows", []),
        "results": ordered,
        "top_candidates": ordered[:3],
    }

    json_path = out_dir / "search_report.json"
    json_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")

    lines = [
        "# Tandem Preset Search",
        "",
        f"- search id: `{search_id}`",
        f"- base job: `{base_job['job_id']}`",
        f"- input: `{base_job['request']['input_path']}`",
        "",
    ]
    if base_report.get("focus_windows"):
        lines.extend(["## Focus Windows", ""])
        for index, window in enumerate(base_report["focus_windows"][:5], start=1):
            lines.append(
                f"- {index}. `{window['start']:.2f}-{window['end']:.2f}` | difficulty `{window['difficulty_score']:.2f}` | text `{window['text']}`"
            )
        lines.append("")

    lines.extend(["## Ranking", ""])
    for index, item in enumerate(ordered, start=1):
        lines.extend(
            [
                f"### {index}. {item['candidate']['slug']}",
                "",
                f"- label: `{item['candidate']['label']}`",
                f"- mode: `{item['mode']}`",
                f"- job: `{item['job_id']}`",
                f"- score: `{item['score']:.3f}`",
                f"- issues: {', '.join(item['issues']) or 'none'}",
                f"- final vocal bleed: `{item['metrics']['final_mix_vocal_bleed_db']:.2f} dB`",
                f"- warble centroid ratio: `{item['metrics']['warble_centroid_ratio']:.3f}`",
                f"- warble hi4 ratio: `{item['metrics']['warble_hi4_ratio']:.3f}`",
                f"- final source corr: `{item['metrics']['final_source_corr']:.4f}`",
                f"- openness centroid delta: `{item['metrics']['openness_centroid_delta_hz']:.1f} Hz`",
            ]
        )
        if item["metrics"].get("reference_usable"):
            lines.extend(
                [
                    f"- reference diff vs rms: `{item['metrics']['reference_diff_vs_rms_db']:.2f} dB`",
                    f"- reference corr: `{item['metrics']['reference_corr']:.3f}`",
                ]
            )
        if item["metrics"].get("lyrics_coverage_ratio", 0.0) > 0:
            lines.extend(
                [
                    f"- lyrics coverage: `{item['metrics']['lyrics_coverage_ratio']:.3f}`",
                    f"- lyrics focus: `{item['metrics']['lyrics_focus_ratio']:.3f}`",
                    f"- lyrics high-activity coverage: `{item['metrics']['lyrics_high_activity_coverage_ratio']:.3f}`",
                ]
            )
        lines.append("")

    md_path = out_dir / "search_report.md"
    md_path.write_text("\n".join(lines), encoding="utf-8")
    return json_path, md_path


def run_search(
    *,
    root: Path,
    base_job_id: str,
    max_candidates: int,
    poll_sec: float,
    wait_idle: bool,
    lyrics_validate_top_k: int,
    output_dir: Path | None = None,
    search_id: str | None = None,
    reference_instrumental_path: Path | None = None,
    force_reference_target: bool = False,
) -> dict[str, str]:
    root = root.resolve()
    base_job = read_job(root, base_job_id)
    resolved_reference = reference_instrumental_path.resolve() if reference_instrumental_path else None
    base_report = analyze_job(
        root,
        base_job_id,
        reference_instrumental_path=resolved_reference,
        force_reference_target=force_reference_target,
    )
    write_report(root, base_report)
    focus_windows = base_report.get("focus_windows", [])

    resolved_search_id = search_id or (time.strftime("%Y%m%d_%H%M%S") + "_" + uuid.uuid4().hex[:6])
    out_dir = output_dir.resolve() if output_dir else (root / ".tmp" / "preset-search" / resolved_search_id)
    generated_dir = out_dir / "generated_presets"
    out_dir.mkdir(parents=True, exist_ok=True)
    generated_dir.mkdir(parents=True, exist_ok=True)

    candidates = CANDIDATES[: max(1, max_candidates)]
    results: list[dict[str, Any]] = []
    submitted_jobs: set[str] = set()

    for candidate in candidates:
        if wait_idle:
            wait_until_idle(root, submitted_jobs, poll_sec)

        preset_name = f"autosearch_{resolved_search_id}_{candidate['slug']}"
        preset_data = make_search_preset(base_job["preset"], candidate, preset_name, include_lyrics=False)
        archive_generated_preset(generated_dir, preset_name, preset_data)

        payload = build_request_from_job(
            base_job,
            preset_name,
            resolved_search_id,
            candidate["slug"],
            enable_lyrics=False,
            preset_override=preset_data,
        )
        created_job = api_request("POST", "/api/v1/jobs", payload)
        job_id = created_job["job_id"]
        submitted_jobs.add(job_id)
        print(f"[submit] {candidate['slug']} -> {job_id}", flush=True)

        finished_job = wait_for_job(job_id, poll_sec)
        if finished_job["status"] != "completed":
            results.append(
                {
                    "candidate": candidate,
                    "job_id": job_id,
                    "status": finished_job["status"],
                    "score": float("-inf"),
                    "issues": ["job_failed"],
                    "metrics": {},
                    "score_breakdown": {},
                    "report_path": None,
                    "mode": "coarse",
                }
            )
            continue

        report = analyze_job(
            root,
            job_id,
            focus_windows=focus_windows,
            reference_instrumental_path=resolved_reference,
            force_reference_target=force_reference_target,
        )
        report_path, _ = write_report(root, report)
        results.append(summarize_result(candidate, finished_job, report, report_path, mode="coarse"))

    ordered = sorted(results, key=lambda item: item.get("score", float("-inf")), reverse=True)
    for result in ordered[: max(0, min(lyrics_validate_top_k, len(ordered)))]:
        candidate = result["candidate"]
        if wait_idle:
            wait_until_idle(root, submitted_jobs, poll_sec)

        preset_name = f"autosearch_{resolved_search_id}_{candidate['slug']}_full"
        preset_data = make_search_preset(base_job["preset"], candidate, preset_name, include_lyrics=True)
        archive_generated_preset(generated_dir, preset_name, preset_data)

        payload = build_request_from_job(
            base_job,
            preset_name,
            resolved_search_id,
            f"{candidate['slug']}_full",
            enable_lyrics=True,
            preset_override=preset_data,
        )
        created_job = api_request("POST", "/api/v1/jobs", payload)
        job_id = created_job["job_id"]
        submitted_jobs.add(job_id)
        print(f"[validate] {candidate['slug']} -> {job_id}", flush=True)

        finished_job = wait_for_job(job_id, poll_sec)
        if finished_job["status"] != "completed":
            continue

        report = analyze_job(
            root,
            job_id,
            focus_windows=focus_windows,
            reference_instrumental_path=resolved_reference,
            force_reference_target=force_reference_target,
        )
        report_path, _ = write_report(root, report)
        updated = summarize_result(candidate, finished_job, report, report_path, mode="validated", previous=result)
        results[results.index(result)] = updated

    json_path, md_path = write_search_report(out_dir, resolved_search_id, base_job, base_report, results)
    return {"search_id": resolved_search_id, "json": str(json_path), "markdown": str(md_path)}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--base-job", required=True, help="Completed tandem job id used as the search baseline/input source")
    parser.add_argument("--max-candidates", type=int, default=4, help="How many built-in candidate variants to run")
    parser.add_argument("--poll-sec", type=float, default=10.0)
    parser.add_argument("--lyrics-validate-top-k", type=int, default=2)
    parser.add_argument("--search-id", default=None)
    parser.add_argument("--output-dir", type=Path, default=None)
    parser.add_argument("--wait-until-idle", action="store_true", default=True)
    parser.add_argument("--skip-wait-until-idle", dest="wait_until_idle", action="store_false")
    parser.add_argument("--reference-instrumental", type=Path, default=None)
    parser.add_argument("--force-reference-target", action="store_true")
    args = parser.parse_args()

    result = run_search(
        root=args.root,
        base_job_id=args.base_job,
        max_candidates=args.max_candidates,
        poll_sec=args.poll_sec,
        wait_idle=args.wait_until_idle,
        lyrics_validate_top_k=args.lyrics_validate_top_k,
        output_dir=args.output_dir,
        search_id=args.search_id,
        reference_instrumental_path=args.reference_instrumental,
        force_reference_target=args.force_reference_target,
    )
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(130)
